interface Seed {
  n: number;
  slug: string;
  bnName: string;
  bnTitle: string;
  bnBio: string;
  categoryIds: string[];
  areaId: string;
  serviceAreaIds: string[];
  rating: number;
  reviewCount: number;
  completedJobs: number;
  isVerified: boolean;
  experienceYears: number;
  responseMinutes: number;
  priceFrom: number;
  categoryPricing: Record<string, number>;
  bnBadges: string[];
  joinedAt: string;
  isFeatured?: boolean;
  availability?: Availability;
  portfolio: [string, string][];
  phoneTail: string;
}

function build(s: Seed): Provider {
  return {
    _id: `prv-${String(s.n).padStart(4, "0")}`,
    slug: s.slug,
    bnName: s.bnName,
    bnTitle: s.bnTitle,
    bnBio: s.bnBio,
    phone: `017${s.phoneTail}`,
    categoryIds: s.categoryIds,
    areaId: s.areaId,
    serviceAreaIds: s.serviceAreaIds,
    rating: s.rating,
    reviewCount: s.reviewCount,
    completedJobs: s.completedJobs,
    isVerified: s.isVerified,
    status: "active",
    experienceYears: s.experienceYears,
    responseMinutes: s.responseMinutes,
    priceFrom: s.priceFrom,
    categoryPricing: s.categoryPricing,
    activeCategoryIds: s.categoryIds,
    portfolio: s.portfolio.map(([categoryId, bnCaption], i) => ({
      id: `prv-${String(s.n).padStart(4, "0")}-p${i + 1}`,
      categoryId,
      bnCaption,
    })),
    bnBadges: s.bnBadges,
    joinedAt: s.joinedAt,
    isFeatured: s.isFeatured ?? false,
    availability: s.availability ?? FULL_WEEK,
    ...meta(s.joinedAt, "2026-03-12T17:20"),
  };
}

