/**
 * Seed professionals.
 *
 * Authoring rules that matter more than they look:
 *  - ratings run 3.6–5.0, never all 4.8. Uniform ratings are the fastest way
 *    for a marketplace to read as fake;
 *  - response times, job counts and joining dates all vary;
 *  - a few providers are deliberately unverified or newly joined, so the
 *    verified badge and the admin verification queue both have something real
 *    to show;
 *  - names, areas and prices are Chattogram-plausible.
 */

